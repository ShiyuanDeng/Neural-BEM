def test_common_ordered_geometry_reaches_both_forward_solvers_and_mie(
    circle_case: SimpleNamespace,
) -> None:
    model = CircleSDF2D(center=TARGET_CENTER, radius=TARGET_RADIUS)
    results = {
        solver: predict_paired_response(
            model,
            circle_case.problem,
            circle_case.geometry_config,
            solver=solver,
        )
        for solver in ("mod", "kress")
    }

    for result in results.values():
        assert result.scattered_response.shape == (6, 2)
        assert result.total_response.shape == (6, 2)
        assert np.all(np.isfinite(result.scattered_response))
        assert np.max(result.linear_system_relative_residuals) < 1.0e-12
        assert result.geometry_build.maximum_curve_sdf_residual < 1.0e-8

    # Both adapters must see exactly the same ordered nodes and arc weights.
    np.testing.assert_allclose(
        results["mod"].geometry_build.curve.points,
        results["kress"].geometry_build.curve.points,
        atol=2.0e-14,
        rtol=0.0,
    )
    np.testing.assert_allclose(
        results["mod"].geometry_build.curve.arc_length_weights,
        results["kress"].geometry_build.curve.arc_length_weights,
        atol=2.0e-14,
        rtol=0.0,
    )

    curve = results["kress"].geometry_build.curve
    mod_boundary = ordered_curve_to_mod_boundary(
        curve, circle_case.geometry_config.bounds
    )
    mod_points = mod_boundary.points.detach().cpu().numpy()
    mod_normals = mod_boundary.normals.detach().cpu().numpy()
    ordinary_weights = (
        mod_boundary.quadrature_weights.detach().cpu().numpy().reshape(-1)
    )
    strict_weights = (
        mod_boundary.strict_quadrature_weights.detach().cpu().numpy().reshape(-1)
    )
    np.testing.assert_allclose(mod_points, curve.points, atol=0.0, rtol=0.0)
    np.testing.assert_allclose(mod_normals, curve.normals, atol=0.0, rtol=0.0)
    np.testing.assert_allclose(
        ordinary_weights, curve.arc_length_weights, atol=0.0, rtol=0.0
    )
    np.testing.assert_allclose(
        strict_weights, curve.arc_length_weights, atol=0.0, rtol=0.0
    )
    assert not np.shares_memory(mod_points, curve.points)
    assert not np.shares_memory(mod_normals, curve.normals)
    assert mod_boundary.quadrature_weights.data_ptr() != (
        mod_boundary.strict_quadrature_weights.data_ptr()
    )

    errors = {
        solver: float(
            np.linalg.norm(result.scattered_response - circle_case.exact_scattered)
            / np.linalg.norm(circle_case.exact_scattered)
        )
        for solver, result in results.items()
    }
    assert errors["mod"] < 2.0e-2, errors
    assert errors["kress"] < 1.0e-6, errors
    assert errors["kress"] < 1.0e-3 * errors["mod"], errors


@pytest.mark.parametrize(
    ("solver", "maximum_final_relative_error"),
    (("mod", 1.0e-2), ("kress", 1.0e-4)),
)
def test_wrong_circle_recovers_with_monotone_fixed_objective(
    solver: str,
    maximum_final_relative_error: float,
    circle_case: SimpleNamespace,
) -> None:
    model = CircleSDF2D(
        center=INITIAL_CENTER,
        radius=INITIAL_RADIUS,
        dtype=torch.float64,
    )
    controller = build_circle_parameter_controller(
        model,
        center_bounds=((0.4, 0.6), (0.4, 0.6)),
        radius_bounds=(0.025, 0.09),
    )
    data = ComplexScatteredData(
        forward_problem=circle_case.problem,
        observed_scattered_response=circle_case.exact_scattered,
    )
    inverse = run_parameter_fd_inverse(
        model,
        controller,
        data,
        circle_case.geometry_config,
        solver=solver,
        config=ParameterFDConfig(
            max_iterations=5,
            finite_difference_steps=np.array([5.0e-5, 5.0e-5, 4.0e-4]),
            max_steps=np.array([1.0e-2, 1.0e-2, 1.0e-1]),
            initial_damping=1.0e-3,
            max_damping_trials=6,
            max_backtracks=8,
            gradient_tolerance=1.0e-9,
            loss_tolerance=1.0e-14,
            relative_step_tolerance=1.0e-9,
        ),
    )

    losses = np.array([iteration.loss for iteration in inverse.iterations])
    assert losses.size >= 4
    assert np.all(np.diff(losses) <= 32.0 * np.finfo(np.float64).eps)
    assert losses[0] / losses[-1] > 1.0e3
    assert inverse.final_iteration.relative_l2_error < maximum_final_relative_error
    assert max(
        iteration.maximum_system_residual for iteration in inverse.iterations
    ) < 1.0e-12
    assert inverse.maximum_system_residual < 1.0e-12

    physical = inverse.final_iteration.physical_parameters
    center_error = math.hypot(
        physical["center_x"] - TARGET_CENTER[0],
        physical["center_y"] - TARGET_CENTER[1],
    )
    radius_error = abs(physical["radius"] - TARGET_RADIUS)
    assert center_error < 5.0e-4
    assert radius_error < 5.0e-4
    np.testing.assert_allclose(
        controller.parameter_vector(), inverse.final_iteration.parameter_vector
    )



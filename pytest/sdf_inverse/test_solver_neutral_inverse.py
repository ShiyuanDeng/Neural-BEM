TARGET_CENTER = (0.5, 0.5)
TARGET_RADIUS = 0.05
INITIAL_CENTER = (0.49, 0.51)
INITIAL_RADIUS = 0.06


@pytest.fixture(scope="module")
def circle_case() -> SimpleNamespace:
    """Small non-degenerate paired experiment with an independent oracle."""

    angles = np.linspace(0.0, 2.0 * np.pi, 6, endpoint=False, dtype=np.float64)
    standoff = 0.30
    angular_separation = float(cfg.TX_RX_OFFSET) / standoff
    sources = np.column_stack(
        (
            TARGET_CENTER[0] + standoff * np.cos(angles),
            TARGET_CENTER[1] + standoff * np.sin(angles),
        )
    )
    receivers = np.column_stack(
        (
            TARGET_CENTER[0] + standoff * np.cos(angles + angular_separation),
            TARGET_CENTER[1] + standoff * np.sin(angles + angular_separation),
        )
    )
    angular_frequencies = 2.0 * np.pi * np.array([0.25e9, 0.50e9])
    exterior_spec = MaterialSpec(epsr=cfg.SAND_EPSR, sigma=cfg.SAND_SIGMA)
    interior_spec = MaterialSpec(epsr=cfg.PLASTIC_EPSR, sigma=cfg.PLASTIC_SIGMA)
    problem = PairedForwardProblem(
        source_points=sources,
        receiver_points=receivers,
        angular_frequencies=angular_frequencies,
        source_strengths=1.0 + 0.0j,
        exterior=exterior_spec,
        interior=interior_spec,
        eps0=cfg.EPS0,
        mu0=cfg.MU0,
    )
    exact_scattered = penetrable_cylinder_frequency_response(
        receivers,
        sources,
        angular_frequencies,
        1.0 + 0.0j,
        exterior=Material(epsr=cfg.SAND_EPSR, sigma=cfg.SAND_SIGMA),
        interior=Material(epsr=cfg.PLASTIC_EPSR, sigma=cfg.PLASTIC_SIGMA),
        eps0=cfg.EPS0,
        mu0=cfg.MU0,
        radius=TARGET_RADIUS,
        center=TARGET_CENTER,
        include_incident=False,
    )
    geometry_config = OrderedSDFGeometryConfig(
        bounds=((0.35, 0.35), (0.65, 0.65)),
        # This spacing avoids placing the circle's cardinal points exactly on
        # marching-squares vertices while retaining a cheap deterministic fit.
        grid_shape=(65, 65),
        projected_samples=32,
        bandwidth=4,
        num_nodes=32,
        arclength_dense_resolution=64,
        validation_resolution=64,
    )
    return SimpleNamespace(
        problem=problem,
        exact_scattered=exact_scattered,
        geometry_config=geometry_config,
    )


def test_circle_sdf_and_bounded_parameter_controller() -> None:
    model = CircleSDF2D(
        center=INITIAL_CENTER,
        radius=INITIAL_RADIUS,
        dtype=torch.float64,
    )
    points = torch.tensor(
        [INITIAL_CENTER, (INITIAL_CENTER[0] + INITIAL_RADIUS, INITIAL_CENTER[1])],
        dtype=torch.float64,
    )
    np.testing.assert_allclose(
        model(points).detach().cpu().numpy().reshape(-1),
        [-INITIAL_RADIUS, 0.0],
        atol=2.0e-15,
    )

    controller = build_circle_parameter_controller(
        model,
        center_bounds=((0.4, 0.6), (0.4, 0.6)),
        radius_bounds=(0.025, 0.09),
    )
    assert controller.names == ("center_x", "center_y", "log_radius")
    np.testing.assert_allclose(
        controller.parameter_vector(),
        [*INITIAL_CENTER, math.log(INITIAL_RADIUS)],
        atol=0.0,
        rtol=2.0e-15,
    )

    updated = np.array([0.51, 0.49, math.log(0.055)], dtype=np.float64)
    controller.assign(updated)
    np.testing.assert_allclose(controller.parameter_vector(), updated)
    assert controller.physical_parameter_dict() == pytest.approx(
        {"center_x": 0.51, "center_y": 0.49, "radius": 0.055}
    )
    projected = controller.project(np.array([0.8, 0.2, math.log(0.2)]))
    np.testing.assert_allclose(
        projected,
        [controller.upper_bounds[0], controller.lower_bounds[1], controller.upper_bounds[2]],
    )

    large_model = torch.nn.Linear(2, 16, dtype=torch.float64)
    with pytest.raises(ValueError, match="adjoint"):
        TorchParameterController(
            large_model,
            lower_bounds=-1.0,
            upper_bounds=1.0,
            max_parameters=32,
        )


def test_single_frequency_residual_is_not_erased() -> None:
    observed = np.array([[1.0 + 2.0j], [2.0 - 1.0j]])
    predicted = observed + np.array([[0.1 - 0.2j], [-0.3 + 0.4j]])

    residual, relative_l2 = normalized_complex_residual(predicted, observed)

    assert residual.shape == (4,)
    assert np.linalg.norm(residual) > 0.0
    assert relative_l2 == pytest.approx(
        np.linalg.norm(predicted - observed) / np.linalg.norm(observed)
    )


def test_grid_aligned_exact_zero_vertices_do_not_break_contour_extraction() -> None:
    """Exact grid zeros may repeat marching-squares vertices, but not geometry."""

    geometry = build_ordered_sdf_geometry(
        CircleSDF2D(center=TARGET_CENTER, radius=TARGET_RADIUS),
        OrderedSDFGeometryConfig(
            bounds=((0.35, 0.35), (0.65, 0.65)),
            # h=0.005 m and radius=10h: cardinal zero-set points are grid nodes.
            grid_shape=(61, 61),
            projected_samples=32,
            bandwidth=4,
            num_nodes=32,
            arclength_dense_resolution=64,
            validation_resolution=64,
        ),
    )

    assert geometry.curve.num_nodes == 32
    assert geometry.maximum_curve_sdf_residual < 1.0e-8


def test_artifact_directory_requires_explicit_overwrite(tmp_path) -> None:
    output = tmp_path / "inverse-run"
    output.mkdir()
    known_artifact = output / "metrics.json"
    unrelated_file = output / "keep-me.txt"
    known_artifact.write_text("stale", encoding="utf-8")
    unrelated_file.write_text("unrelated", encoding="utf-8")


@pytest.mark.parametrize("kind", ("ellipse", "random_features"))
def test_non_distance_initial_models_are_noncircular_regular_closed_fields(
    kind: str,
    noncircle_geometry_config: OrderedSDFGeometryConfig,
) -> None:
    model, controller = _build_initial_model(kind)
    geometry = build_ordered_sdf_geometry(model, noncircle_geometry_config)
    physical = controller.physical_parameter_dict()
    radii = np.linalg.norm(
        geometry.curve.points
        - np.array([physical["center_x"], physical["center_y"]])[None, :],
        axis=1,
    )
    assert np.ptp(radii) >= 2.0e-3
    assert geometry.maximum_normalized_curve_residual < 2.0e-4

    points = torch.tensor(
        geometry.curve.points,
        dtype=torch.float64,
        requires_grad=True,
    )
    values = model(points).reshape(-1)
    gradients = torch.autograd.grad(values.sum(), points)[0]
    maximum_unit_deviation = torch.max(
        torch.abs(torch.linalg.norm(gradients, dim=1) - 1.0)
    )
    assert float(maximum_unit_deviation) >= 5.0e-2
    assert getattr(model, "claims_signed_distance") is False


def test_non_distance_model_controllers_round_trip_and_random_features_repeat() -> None:
    ellipse = EllipseLevelSet2D(
        center=(0.48, 0.52),
        semi_axes=(0.072, 0.038),
        rotation_radians=0.4,
    )
    ellipse_controller = build_ellipse_parameter_controller(
        ellipse,
        center_bounds=((0.4, 0.6), (0.4, 0.6)),
        semi_axis_bounds=(0.025, 0.09),
    )
    ellipse_vector = ellipse_controller.parameter_vector()
    ellipse_controller.assign(ellipse_vector)
    np.testing.assert_array_equal(
        ellipse_controller.parameter_vector(), ellipse_vector
    )

    first = RadialRandomFeatureImplicit2D(random_seed=17, radius=0.06)
    second = RadialRandomFeatureImplicit2D(random_seed=17, radius=0.06)
    first_controller = build_radial_random_feature_parameter_controller(
        first,
        center_bounds=((-0.1, 0.1), (-0.1, 0.1)),
        radius_bounds=(0.025, 0.075),
    )
    assert first_controller.num_parameters == 7
    points = torch.tensor(
        [[0.06, 0.0], [0.0, 0.06], [-0.04, 0.03]], dtype=torch.float64
    )
    torch.testing.assert_close(first(points), second(points), rtol=0.0, atol=0.0)
    torch.testing.assert_close(
        first.hidden_weights, second.hidden_weights, rtol=0.0, atol=0.0
    )


def test_unconstrained_random_mlp_fails_before_forward_solve(
    noncircle_geometry_config: OrderedSDFGeometryConfig,
) -> None:
    torch.manual_seed(0)
    model = torch.nn.Sequential(
        torch.nn.Linear(2, 4, dtype=torch.float64),
        torch.nn.Tanh(),
        torch.nn.Linear(4, 1, dtype=torch.float64),
    )
    with pytest.raises(FrontendError):
        build_ordered_sdf_geometry(model, noncircle_geometry_config)


@pytest.mark.parametrize("kind", ("ellipse", "random_features"))
@pytest.mark.parametrize("solver", ("mod", "kress"))
def test_noncircle_initializations_reduce_the_same_mie_objective(
    kind: str,
    solver: str,
    circle_case: SimpleNamespace,
    noncircle_geometry_config: OrderedSDFGeometryConfig,
) -> None:
    model, controller = _build_initial_model(kind)
    inverse = run_parameter_fd_inverse(
        model,
        controller,
        ComplexScatteredData(circle_case.problem, circle_case.exact_scattered),
        noncircle_geometry_config,
        solver=solver,
        config=_inverse_config_for_controller(controller, max_iterations=2),
    )
    losses = np.asarray([record.loss for record in inverse.iterations])
    assert losses.size == 3
    assert np.all(np.diff(losses) < 0.0)
    assert losses[-1] < 0.5 * losses[0]
    assert inverse.maximum_system_residual < 1.0e-10
